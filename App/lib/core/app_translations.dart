  static String translate(Locale locale, String source) {
    final languageCode = locale.languageCode;
    if (languageCode == 'en') return source;

    final values =
        _translations[source] ??
        _additionalTranslations[source] ??
        _moreTranslations[source];
    final languageIndex = languageCode == 'si' ? 0 : 1;
    if (values != null) return values[languageIndex];

    if (source.startsWith('Login to your ') && source.endsWith(' account')) {
      final role = source.substring(14, source.length - 8);
      final translatedRole = translate(locale, role);
      return languageCode == 'si'
          ? '$translatedRole ගිණුමට පිවිසෙන්න'
          : '$translatedRole கணக்கில் உள்நுழைக';
    }
    if (source.startsWith('Create ') && source.endsWith(' Account')) {
      final role = source.substring(7, source.length - 8);
      final translatedRole = translate(locale, role);
      return languageCode == 'si'
          ? '$translatedRole ගිණුම සාදන්න'
          : '$translatedRole கணக்கை உருவாக்கவும்';
    }
    if (source.startsWith('Enter the email address for your ') &&
        source.endsWith(' account to request password recovery.')) {
      return languageCode == 'si'
          ? 'මුරපදය යළි ලබාගැනීමට ඔබේ ගිණුමේ විද්‍යුත් තැපැල් ලිපිනය ඇතුළත් කරන්න.'
          : 'கடவுச்சொல்லை மீட்டெடுக்க உங்கள் கணக்கின் மின்னஞ்சல் முகவரியை உள்ளிடவும்.';
    }

    if (source.startsWith('Back to ') && source.endsWith(' login')) {
      return languageCode == 'si'
          ? 'පිවිසුමට ආපසු යන්න'
          : 'உள்நுழைவுக்குத் திரும்பவும்';
    }
    if (source.startsWith('Hello, ')) {
      final greeting = languageCode == 'si' ? 'ආයුබෝවන්, ' : 'வணக்கம், ';
      return '$greeting${source.substring(7)}';
    }
    if (source.startsWith('Age ')) {
      final ageLabel = languageCode == 'si' ? 'වයස ' : 'வயது ';
      return '$ageLabel${source.substring(4)}';
    }
    if (source.startsWith('Code expires in ')) {
      final prefix = languageCode == 'si'
          ? 'කේතය කල් ඉකුත් වන්නේ '
          : 'குறியீடு காலாவதியாகும் நேரம் ';
      return '$prefix${source.substring(16)}';
    }
    if (source.startsWith('Teacher · ')) {
      final prefix = languageCode == 'si' ? 'ගුරු · ' : 'ஆசிரியர் · ';
      return '$prefix${source.substring(10)}';
    }
    const approvalMessage =
